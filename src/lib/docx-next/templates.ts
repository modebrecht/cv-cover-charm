import type { Alignment, PageMargins } from "./model";

/** Page-width-relative nonsemantic geometry; absent height follows its chrome band. */
export type TemplateMotif = {
  /** Same stacking on first/continuation pages; paper underlay is layer zero. */
  paintLayer?: number;
  shape: "rect" | "circle" | "path";
  path?: string;
  xFraction: number;
  widthFraction: number;
  topMm: number;
  heightMm?: number;
  cornerRadiiMm?: readonly [number, number, number, number];
  /** Omit fill for border-only motifs such as rings. */
  fillSlot?: string;
  /** Fixed nonsemantic paint (e.g. a white bloom), independent of editable palette slots. */
  fillColor?: string;
  stroke?: { slot: string; widthMm: number };
  endSlot?: string;
  gradientStops?: readonly { slot: string; offsetPct: number }[];
  angleDeg?: number;
  radialFade?: { innerPct: number; outerPct: number };
  opacity?: number;
  repeat?: "first" | "continuation";
};

/** Configuration only: templates never receive XML or a package. */
export type TemplateDefinition = {
  /** Compose nonsemantic page geometry into one behind-text asset per header story. */
  pagePaintComposition?: "single-asset";
  id: string;
  archetype: "minimal" | "organic" | "editorial" | "sidebar" | "graphic" | "dark";
  typography: { font: string; bodyPt: number; namePt: number; headingPt: number; heroPt: number };
  colors: { ink: string; accent: string; paper: string };
  margins: PageMargins;
  /** Pure app palette rules resolve readable interior ink/paper independently of cover ink. */
  interiorPaletteSource?: "dossier";
  cover: {
    /** Native cover composition can use its own page gutters. Interior margins remain independent. */
    margins?: PageMargins;
    /** Built-in semantic roles may inherit the dossier font; explicit/custom fonts keep precedence. */
    fontSource?: "dossier";
    order: readonly string[];
    align: Alignment;
    heroSpaceMm: number;
    photoWidthMm: number;
    photoAlign?: Alignment;
    /** Native paragraph defaults; explicit saved field alignment keeps precedence. */
    fieldAlignments?: Readonly<Record<string, Alignment>>;
    /** Palette roles for native field defaults; explicit saved colors retain precedence. */
    fieldColorSlots?: Readonly<Record<string, string>>;
    /** Apply field defaults to palette-bound inline runs; literal authored colors stay explicit. */
    fieldPaletteMode?: "uniform";
    /** Semantic field leads in native flow, including fields grouped in cover cells. */
    fieldSpaceBeforeMm?: Readonly<Record<string, number>>;
    rows?: readonly {
      fields: readonly (string | readonly string[])[];
      widths: readonly number[];
      fillSlot?: string;
      /** Native flowing callout surfaces per cell, independent of absolute page paint. */
      cellFillSlots?: readonly (string | null)[];
      /** Consume solid authored rectangles as growing native surfaces rather than fixed page paint. */
      surfaceElementId?: string;
      /** Consume a solid authored line as the native top edge of this growing row. */
      surfaceBorderElementId?: string;
      cellSurfaceElementIds?: readonly (string | null)[];
      beforeMm?: number;
    }[];
    /** Semantic start of the hero when no photo is present; defaults to the name. */
    heroStartFields?: readonly string[];
    /** Permit the declared hero fields/photo inside a composed native row. */
    heroInRows?: boolean;
    /** Solid authored separator lines participate in native flow beside editable text. */
    flowingRules?: Readonly<Record<string, { beforeMm?: number; afterMm: number }>>;
    heroLeadMm?: number;
    photoAbsentLeadMm?: number;
    decorationPlacement?: "first-header";
    /** Suppress default decorative shapes; explicit saved visibility retains precedence. */
    hiddenDecorationIds?: readonly string[];
    motifs?: readonly TemplateMotif[];
  };
  letter: {
    paragraphSpaceMm: number;
    lineHeight: number;
    recipientGapMm: number;
    fontSource?: "standalone" | "dossier";
    compactMasthead?: { heightMm: number; widthMm: number; fillSlot: string };
    keepTailTogether?: boolean;
  };
  chrome: {
    /** Readable native footer ink on descriptor-owned footer artwork. Explicit text colors win. */
    footerSurfaceSlot?: string;
    headerDistanceMm: number;
    footerDistanceMm: number;
    defaultContact?: { heightMm: number; gapMm: number };
    ignoreEmptyHeader?: boolean;
    lineMetricFactor?: number;
    band?: {
      /** Own semantic descriptor paint instead of the historical browser chrome defaults. */
      surfaceSource?: "descriptor";
      /** Motif-only chrome leaves editable contact text on the paper surface. */
      surface?: "band" | "motifs";
      fillSlot: string;
      accentSlot: string;
      compactFirstMm: number;
      compactContinuationMm: number;
      motifs?: readonly TemplateMotif[];
      /** Quiet page paint when the running header is disabled. */
      noneMotifs?: readonly TemplateMotif[];
      circles?: readonly {
        rightMm: number;
        topMm: number;
        diameterMm: number;
        opacity: number;
        strokeMm?: number;
      }[];
    };
  };
  cv: {
    sectionSpaceMm: number;
    headingRule: boolean;
    sidebarFraction: number;
    /** Default editable heading shading; explicit current/legacy saved choices override it. */
    headingBadge?: boolean;
  };
  /** Quiet page paint independent of running contact chrome; repeats in native header stories. */
  pageMotifs?: Partial<Record<"cover" | "letter" | "cv", readonly TemplateMotif[]>>;
  /** Serialize page paint by declared layers for consistent native importer stacking. */
  pagePaintOrder?: "layer";
  artwork: readonly { asset: string; semanticText: false }[];
};
